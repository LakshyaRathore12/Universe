export interface DriveFileItem {
  id: string;
  name: string;
  mimeType: string;
  webViewLink?: string;
  webContentLink?: string;
  iconLink?: string;
  thumbnailLink?: string;
  size?: string;
  modifiedTime?: string;
  owners?: { displayName: string; emailAddress: string }[];
}

export interface DriveUploadResult {
  success: boolean;
  file?: DriveFileItem;
  message?: string;
}

/**
 * List files from user's Google Drive
 */
export async function fetchDriveFiles(
  accessToken: string,
  options?: {
    searchQuery?: string;
    mimeTypeFilter?: string;
    pageSize?: number;
    folderId?: string;
  }
): Promise<{ files: DriveFileItem[]; nextPageToken?: string }> {
  if (!accessToken) {
    throw new Error('Google Drive access token is required.');
  }

  const queryParts: string[] = ['trashed = false'];

  if (options?.folderId) {
    queryParts.push(`'${options.folderId}' in parents`);
  }

  if (options?.searchQuery && options.searchQuery.trim()) {
    const escaped = options.searchQuery.replace(/'/g, "\\'");
    queryParts.push(`name contains '${escaped}'`);
  }

  if (options?.mimeTypeFilter && options.mimeTypeFilter !== 'all') {
    if (options.mimeTypeFilter === 'documents') {
      queryParts.push(
        "(mimeType = 'application/vnd.google-apps.document' or mimeType = 'application/pdf' or mimeType = 'text/plain' or mimeType contains 'word')"
      );
    } else if (options.mimeTypeFilter === 'spreadsheets') {
      queryParts.push(
        "(mimeType = 'application/vnd.google-apps.spreadsheet' or mimeType = 'text/csv' or mimeType contains 'sheet' or mimeType contains 'excel')"
      );
    } else if (options.mimeTypeFilter === 'presentations') {
      queryParts.push(
        "(mimeType = 'application/vnd.google-apps.presentation' or mimeType contains 'presentation' or mimeType contains 'powerpoint')"
      );
    } else if (options.mimeTypeFilter === 'images') {
      queryParts.push("mimeType contains 'image/'");
    } else if (options.mimeTypeFilter === 'folders') {
      queryParts.push("mimeType = 'application/vnd.google-apps.folder'");
    }
  }

  const q = encodeURIComponent(queryParts.join(' and '));
  const fields = encodeURIComponent(
    'files(id,name,mimeType,webViewLink,webContentLink,iconLink,thumbnailLink,size,modifiedTime,owners),nextPageToken'
  );
  const pageSize = options?.pageSize || 20;

  const url = `https://www.googleapis.com/drive/v3/files?q=${q}&fields=${fields}&pageSize=${pageSize}&orderBy=modifiedTime desc`;

  const res = await fetch(url, {
    headers: {
      Authorization: `Bearer ${accessToken}`,
      Accept: 'application/json',
    },
  });

  if (!res.ok) {
    const errText = await res.text();
    let errorData;
    try {
      errorData = JSON.parse(errText);
    } catch {
      errorData = { error: { message: errText } };
    }
    throw new Error(
      errorData?.error?.message || `Google Drive API error: ${res.status} ${res.statusText}`
    );
  }

  const data = await res.json();
  return {
    files: data.files || [],
    nextPageToken: data.nextPageToken,
  };
}

/**
 * Upload a text / CSV / JSON / Markdown file to Google Drive using multipart upload
 */
export async function uploadFileToDrive(
  accessToken: string,
  fileName: string,
  content: string,
  contentType: string = 'text/csv',
  description?: string
): Promise<DriveUploadResult> {
  if (!accessToken) {
    return { success: false, message: 'Missing Google Drive authentication token.' };
  }

  try {
    const boundary = '-------314159265358979323846';
    const delimiter = `\r\n--${boundary}\r\n`;
    const closeDelimiter = `\r\n--${boundary}--`;

    const metadata = {
      name: fileName,
      mimeType: contentType,
      description: description || 'Generated by UniVerse University Event Management System',
    };

    const multipartRequestBody =
      delimiter +
      'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
      JSON.stringify(metadata) +
      delimiter +
      `Content-Type: ${contentType}; charset=UTF-8\r\n\r\n` +
      content +
      closeDelimiter;

    const response = await fetch(
      'https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,mimeType,webViewLink,webContentLink,iconLink',
      {
        method: 'POST',
        headers: {
          Authorization: `Bearer ${accessToken}`,
          'Content-Type': `multipart/related; boundary=${boundary}`,
        },
        body: multipartRequestBody,
      }
    );

    if (!response.ok) {
      const err = await response.json().catch(() => ({}));
      return {
        success: false,
        message: err?.error?.message || `Upload failed with status ${response.status}`,
      };
    }

    const createdFile: DriveFileItem = await response.json();
    return {
      success: true,
      file: createdFile,
      message: `File "${createdFile.name}" successfully saved to your Google Drive!`,
    };
  } catch (error: any) {
    return {
      success: false,
      message: error?.message || 'Failed to upload file to Google Drive.',
    };
  }
}

/**
 * Delete a file from Google Drive
 */
export async function deleteFileFromDrive(
  accessToken: string,
  fileId: string
): Promise<{ success: boolean; message?: string }> {
  if (!accessToken) {
    return { success: false, message: 'Google Drive access token missing' };
  }

  try {
    const res = await fetch(`https://www.googleapis.com/drive/v3/files/${fileId}`, {
      method: 'DELETE',
      headers: {
        Authorization: `Bearer ${accessToken}`,
      },
    });

    if (!res.ok) {
      const err = await res.json().catch(() => ({}));
      return {
        success: false,
        message: err?.error?.message || `Failed to delete file (HTTP ${res.status})`,
      };
    }

    return { success: true };
  } catch (err: any) {
    return { success: false, message: err?.message || 'Error deleting file from Drive' };
  }
}

/**
 * Helper to export candidate list to Google Drive as CSV
 */
export async function exportCandidateRosterToDrive(
  accessToken: string,
  eventTitle: string,
  clubName: string,
  csvData: string
): Promise<DriveUploadResult> {
  const timestamp = new Date().toISOString().split('T')[0];
  const safeTitle = eventTitle.replace(/[^a-zA-Z0-9_-]/g, '_').substring(0, 30);
  const fileName = `Attendees_${safeTitle}_${timestamp}.csv`;

  return uploadFileToDrive(
    accessToken,
    fileName,
    csvData,
    'text/csv',
    `UniVerse Attendee Roster for "${eventTitle}" hosted by ${clubName}. Exported on ${new Date().toLocaleString()}.`
  );
}

/**
 * Helper to save an event ticket/pass receipt to Google Drive
 */
export async function saveTicketPassToDrive(
  accessToken: string,
  eventTitle: string,
  ticketCode: string,
  userName: string,
  ticketDetails: {
    venue: string;
    dateTime: string;
    studentId?: string;
    department?: string;
  }
): Promise<DriveUploadResult> {
  const fileName = `TicketPass_${ticketCode}_${eventTitle.replace(/[^a-zA-Z0-9]/g, '_').substring(0, 20)}.txt`;
  
  const textReceipt = `
============================================================
              UNIVERSE CAMPUS EVENT PASS
============================================================
Ticket Pass Code   : ${ticketCode}
Event Title        : ${eventTitle}
Venue              : ${ticketDetails.venue}
Date & Time        : ${ticketDetails.dateTime}

Candidate Name     : ${userName}
Enrollment ID      : ${ticketDetails.studentId || 'N/A'}
Department         : ${ticketDetails.department || 'N/A'}

Status             : CONFIRMED RSVP
Issued On          : ${new Date().toLocaleString()}
System             : UniVerse Campus Event Network
============================================================
Please present this pass or ticket code at the entrance verification desk.
`;

  return uploadFileToDrive(
    accessToken,
    fileName,
    textReceipt.trim(),
    'text/plain',
    `Official UniVerse event ticket pass for ${userName} (${ticketCode})`
  );
}

/**
 * Helper to save a verified Participation Certificate to Google Drive
 */
export async function saveCertificateToDrive(
  accessToken: string,
  cert: {
    id: string;
    studentName: string;
    studentId?: string;
    eventTitle: string;
    clubName: string;
    eventDate: string;
    eventVenue: string;
    department?: string;
    issuedAt: string;
    issuedBy: string;
    verificationHash: string;
  }
): Promise<DriveUploadResult> {
  const fileName = `Certificate_${cert.id}_${cert.studentName.replace(/[^a-zA-Z0-9]/g, '_')}.txt`;

  const certDocument = `
================================================================================
           UNIVERSITY OF TECHNOLOGY & SCIENCES - CAMPUS SENATE
                 OFFICIAL CERTIFICATE OF PARTICIPATION
================================================================================

CERTIFICATE ID: ${cert.id}
VERIFICATION HASH: ${cert.verificationHash}

This is to certify that:

                   ${cert.studentName.toUpperCase()}
          (Enrollment No: ${cert.studentId || 'N/A'}, Dept: ${cert.department || 'N/A'})

has actively participated and satisfied verified attendance requirements in:

                   "${cert.eventTitle}"

Organized by    : ${cert.clubName}
Event Date      : ${cert.eventDate}
Campus Venue    : ${cert.eventVenue}
Issued Date     : ${new Date(cert.issuedAt).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}
Authorizing Body: ${cert.issuedBy}

================================================================================
Status: VERIFIED PRESENT & OFFICIALLY ISSUED
Office of Student Welfare, Central Collegiate Council
================================================================================
`;

  return uploadFileToDrive(
    accessToken,
    fileName,
    certDocument.trim(),
    'text/plain',
    `Verified Participation Certificate for ${cert.studentName} - ${cert.eventTitle} (${cert.id})`
  );
}

